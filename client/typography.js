/**
 * Русская типографика: замена уже стоящих обычных пробелов на неразрывные.
 * Модуль никогда не добавляет и не удаляет символы — только меняет U+0020 на U+00A0.
 * Отслеживание: у каждого абзаца хранится подпись проверенного текста (data-typo);
 * пока текст блока не менялся, блок не трогают повторно.
 */
export const NBSP = '\u00A0';
const L = '\\p{L}', D = '\\d';
const shortWords = '(?:\\p{L}{1,2}|для|при|под|над|без|про|или|что|как|чем|так|где|изо|ото|обо|надо|подо|из-за|из-под)';
const units = '(?:г|гг|в|вв|тыс|млн|млрд|руб|коп|пуд|фунт|стр|кг|мг|м|см|мм|км|л|мл|ч|мин|сек|шт|экз|чел|год|года|году|годов|годах|лет|век|века|веке|веков|штук|человек|тысяч|миллион\\p{L}*|миллиард\\p{L}*|рубл\\p{L}*|копе\\p{L}*|пуд\\p{L}*|фунт\\p{L}*|процент\\p{L}*)';
// В каждом правиле ровно одна захватывающая группа — пробел, который нужно заменить.
export const RULES = [
  // Предлоги, союзы, частицы перед словом: «в улей», «и воск», «не будут».
  {name:'short-word', re:new RegExp(`(?<![${L}${D}\\-])${shortWords}( )(?=[${L}${D}«„"(\\[])`, 'dgiu')},
  // Частицы после слова: «так же», «был ли», «если бы».
  {name:'particle', re:new RegExp(`(?<=${L})( )(?=(?:же|ли|бы|б|ж|ль)(?![${L}\\-]))`, 'dgiu')},
  // Разряды чисел: «178 138».
  {name:'digits', re:/(?<=\d)( )(?=\d)/dg},
  // Число и единица измерения, знак рубля, процент, год: «1901 г.», «5 руб.», «12 %».
  {name:'unit', re:new RegExp(`(?<=${D})( )(?=${units}(?![${L}])|[₽%°$€£])`, 'dgiu')},
  // Знак и число: «№ 5», «§ 3», «стр. 12».
  {name:'sign', re:new RegExp(`(?<=(?:^|[^${L}])(?:№|§|стр\\.|гл\\.|рис\\.|табл\\.))( )(?=${D})`, 'dgiu')},
  // Тире не начинает строку: пробел перед тире неразрывный.
  {name:'dash', re:/( )(?=[—–])/dg},
  // Дефис в роли тире: «слово - слово».
  {name:'hyphen-dash', re:/( )(?=-[ \u00A0])/dg},
  // Тире в начале абзаца или после открывающей кавычки уходит вместе со словом.
  {name:'leading-dash', re:/(?<=^|[«„"(\[])[—–]( )/dgu},
  // Сокращения: «т. е.», «т. д.», «т. п.», «т. к.».
  {name:'abbreviation', re:new RegExp(`(?<=(?:^|[^${L}])т\\.)( )(?=(?:е|д|п|к|н|о)\\.)`, 'dgiu')},
  // Инициалы: «И. И. Иванов».
  {name:'initials', re:/(?<=(?:^|\P{L})[А-ЯЁ]\.)( )(?=[А-ЯЁ])/dgu}
];
/** Индексы пробелов, которые нужно сделать неразрывными. */
export function nbspIndices(text) {
  const out = new Set();
  for (const {re} of RULES) {
    re.lastIndex = 0;
    for (const match of text.matchAll(re)) {
      const at = match.indices[1][0];
      if (text[at] === ' ') out.add(at);
    }
  }
  return [...out].sort((a, b) => a - b);
}
/** Текст с неразрывными пробелами по правилам; длина строки не меняется. */
export function applyNbsp(text) {
  const chars = text.split('');
  for (const at of nbspIndices(text)) chars[at] = NBSP;
  return chars.join('');
}
/** Подпись проверенного текста (FNV-1a, 32 бита). */
export function signature(text) {
  let hash = 0x811c9dc5;
  for (let i = 0; i < text.length; i++) {
    hash ^= text.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193) >>> 0;
  }
  return hash.toString(36);
}
